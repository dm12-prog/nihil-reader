#!/usr/bin/env python3
"""Turn a TrueType font into grey bitmaps for core/reader.h.

usage: gen_font.py <font.ttf> <pixel size> <c name> [darken] >> core/font_data.h
Each pixel is stored as ink amount 0..15 (0 = paper, 15 = full black).
darken < 1 makes the strokes a little heavier (e-ink text looks thin otherwise).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

path, size, name = sys.argv[1], int(sys.argv[2]), sys.argv[3]
darken = float(sys.argv[4]) if len(sys.argv) > 4 else 1.0
font = ImageFont.truetype(path, size)
ascent, descent = font.getmetrics()
chars = list(range(32, 127)) + list(range(160, 256)) + [0x152, 0x153, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2122]
glyphs, data = [], bytearray()
for cp in chars:
    ch = chr(cp)
    adv = round(font.getlength(ch))
    img = Image.new("L", (size * 3, size * 3), 0)
    ImageDraw.Draw(img).text((size, size), ch, font=font, fill=255)
    box = img.getbbox()
    if box is None:
        glyphs.append((cp, 0, 0, 0, 0, adv, len(data)))
        continue
    x0, y0, x1, y1 = box
    glyphs.append((cp, x1 - x0, y1 - y0, x0 - size, y0 - size, adv, len(data)))
    data.extend(round(15 * (p / 255) ** darken) for p in img.crop(box).tobytes())

print("/* %s: %s at %d px, darken %.2f. Generated by tools/font/gen_font.py. Do not edit. */" % (name, path.split("/")[-1], size, darken))
print("static const struct glyph %s_glyphs[%d] = {" % (name, len(glyphs)))
for g in glyphs:
    print("    {0x%04X, %d, %d, %d, %d, %d, %d}," % g)
print("};\nstatic const uint8_t %s_ink[%d] = {" % (name, len(data)))
for i in range(0, len(data), 40):
    print("    " + ",".join(str(b) for b in data[i:i + 40]) + ",")
print("};")
print("static const struct font %s = { %d, %d, %d, %d, %s_glyphs, %s_ink };\n" % (name, size, ascent, descent, len(glyphs), name, name))
