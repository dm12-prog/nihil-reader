#!/usr/bin/env python3
"""Turn a TrueType font into core/font_data.h: one grey bitmap per character.

usage: gen_font.py <font.ttf> <pixel size> > core/font_data.h
Each pixel is stored as ink amount 0..15 (0 = paper, 15 = full black).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

path, size = sys.argv[1], int(sys.argv[2])
font = ImageFont.truetype(path, size)
ascent, descent = font.getmetrics()
chars = list(range(32, 127)) + list(range(160, 256)) + [0x152, 0x153, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026]
glyphs, data = [], bytearray()
for cp in chars:
    ch = chr(cp)
    adv = round(font.getlength(ch))
    img = Image.new("L", (size * 3, size * 3), 0)
    ImageDraw.Draw(img).text((size, size), ch, font=font, fill=255)
    box = img.getbbox()
    if box is None:
        glyphs.append((cp, 0, 0, 0, 0, adv, len(data)))
        continue
    x0, y0, x1, y1 = box
    crop = img.crop(box)
    glyphs.append((cp, x1 - x0, y1 - y0, x0 - size, y0 - size, adv, len(data)))
    data.extend((p * 15 + 127) // 255 for p in crop.getdata())

print("/* Generated by tools/font/gen_font.py from %s at %d px. Do not edit. */" % (path.split("/")[-1], size))
print("#pragma once\n#include <stdint.h>")
print("#define FONT_SIZE %d\n#define FONT_ASCENT %d\n#define FONT_DESCENT %d\n#define FONT_GLYPHS %d" % (size, ascent, descent, len(glyphs)))
print("struct glyph { uint16_t cp; uint8_t w, h; int8_t xoff, yoff; uint8_t adv; uint32_t off; };")
print("static const struct glyph font_glyphs[FONT_GLYPHS] = {")
for g in glyphs:
    print("    {0x%04X, %d, %d, %d, %d, %d, %d}," % g)
print("};\nstatic const uint8_t font_ink[%d] = {" % len(data))
for i in range(0, len(data), 32):
    print("    " + ",".join(str(b) for b in data[i:i + 32]) + ",")
print("};")
